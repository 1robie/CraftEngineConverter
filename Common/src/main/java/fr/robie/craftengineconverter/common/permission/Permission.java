package fr.robie.craftengineconverter.common.permission;

import java.util.Locale;

public enum Permission {
    COMMAND_USE("Allows the user to use the main command of the plugin."),
    COMMAND_RELOAD("Allows the user to reload the plugin configuration."),
    COMMAND_CONVERT("Allows the user to convert assets for CraftEngine"),
    COMMAND_CLEARFILESCACHE("Allows the user to clear the file cache used by the plugin."),
    COMMAND_WORLDCONVERTER("Allows the user to convert world blocks from other plugins"),
    COMMAND_WORLDCONVERTER_START("Allows the user to start a world conversion process"),
    COMMAND_WORLDCONVERTER_CLEAR_CACHED_CHUNKS("Allows the user to clear processed chunks cache"),
    COMMAND_WORLDCONVERTER_RESTORE("Allows the user to restore converted blocks/entities to their original state"),

    NEXO_BLOCK_INTERACT_CONVERSION("Allows the user to convert Nexo blocks on interaction"),
    NEXO_FURNITURE_INTERACT_CONVERSION("Allows the user to convert Nexo furniture on interaction"),

    ITEMSADDER_BLOCK_INTERACT_CONVERSION("Allows the user to convert ItemsAdder blocks on interaction"),
    ITEMSADDER_FURNITURE_INTERACT_CONVERSION("Allows the user to convert ItemsAdder furniture on interaction"),

    COMMAND_BEDROCK_CONVERT("Allows the user to run the Bedrock Edition resource pack conversion");
    private final String description;
    private final String[] args;

    Permission() {
        this.description = "";
        this.args = new String[0];
    }

    Permission(String description, String... args) {
        this.description = description;
        this.args = args;
    }

    /**
     * Generates the permission string for this enum constant.
     * Converts the enum constant name to lowercase and replaces underscores with periods.
     *
     * @return The permission string.
     */
    public String asPermission() {
        return "craftengineconverter." + this.name().toLowerCase(Locale.ROOT).replace("_", ".");
    }

    public String toPermission() {
        StringBuilder builder = new StringBuilder(this.asPermission());
        for (int i = 0; i < this.args.length; i++) {
            builder.append("<");
            builder.append(this.args[i]);
            builder.append(">");
            if (i < this.args.length - 1) {
                builder.append(".");
            }
        }
        return builder.toString();
    }

    /**
     * Generates a permission string for this enum constant with an additional suffix.
     * Appends the specified suffix to the permission string generated by {@link #asPermission()}.
     *
     * @param with The suffix to append.
     * @return The permission string with the suffix.
     */
    public String asPermission(String with) {
        return this.asPermission() + with;
    }

    public String getDescription() {
        return this.description;
    }

    public String[] getArgs() {
        return this.args;
    }
}
